def create_controller(n, shape):

    e = ctrl.Antecedent(
        np.arange(-10, 11, 1), 'error'
    )

    h = ctrl.Consequent(
        np.arange(0, 101, 1), 'heater'
    )

    input_points = np.linspace(-10, 10, n)
    output_points = np.linspace(0, 100, n)

    # Create Membership Functions
    for i in range(n):

        if shape == 'triangular':

            if i == 0:
                ep = [input_points[0], input_points[0], input_points[1]]
                hp = [output_points[0], output_points[0], output_points[1]]

            elif i == n - 1:
                ep = [input_points[-2], input_points[-1], input_points[-1]]
                hp = [output_points[-2], output_points[-1], output_points[-1]]

            else:
                ep = [input_points[i-1], input_points[i], input_points[i+1]]
                hp = [output_points[i-1], output_points[i], output_points[i+1]]

            e[f's{i}'] = fuzz.trimf(e.universe, ep)
            h[f's{i}'] = fuzz.trimf(h.universe, hp)

        elif shape == 'trapezoidal':

            if i == 0:
                ep = [input_points[0], input_points[0],
                      input_points[0], input_points[1]]
                hp = [output_points[0], output_points[0],
                      output_points[0], output_points[1]]

            elif i == n - 1:
                ep = [input_points[-2], input_points[-1],
                      input_points[-1], input_points[-1]]
                hp = [output_points[-2], output_points[-1],
                      output_points[-1], output_points[-1]]

            else:
                ep = [input_points[i-1], input_points[i],
                      input_points[i], input_points[i+1]]
                hp = [output_points[i-1], output_points[i],
                      output_points[i], output_points[i+1]]

            e[f's{i}'] = fuzz.trapmf(e.universe, ep)
            h[f's{i}'] = fuzz.trapmf(h.universe, hp)

    # Create Fuzzy Rules
    rules = []

    for i in range(n):
        rules.append(
            ctrl.Rule(e[f's{i}'], h[f's{i}'])
        )

    return ctrl.ControlSystem(rules)


print("Controller function created successfully!")


def run_experiment(n, shape):

    system = create_controller(n, shape)

    target = 23
    temp = 16

    temperatures = []
    powers = []

    for minute in range(120):

        error_value = np.clip(target - temp, -10, 10)

        sim = ctrl.ControlSystemSimulation(system)

        sim.input['error'] = error_value
        sim.compute()

        power = sim.output['heater']

        # Room temperature model
        temp += (
            0.5 * power / 100
            - 0.05 * (temp - 18)
        )

        temperatures.append(temp)
        powers.append(power)

    return temperatures, powers


