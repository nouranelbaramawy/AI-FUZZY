import numpy as np
import matplotlib.pyplot as plt
import skfuzzy as fuzz
import skfuzzy.control as ctrl



# Define Input
error = ctrl.Antecedent(
    np.arange(-10, 11, 1), 'error'
)

# Define Output
heater = ctrl.Consequent(
    np.arange(0, 101, 1), 'heater'
)

print("Input and Output defined successfully!")



# Input Membership Functions

error['Negative'] = fuzz.trimf(
    error.universe, [-10, -10, 0]
)

error['Zero'] = fuzz.trimf(
    error.universe, [-5, 0, 5]
)

error['Positive'] = fuzz.trimf(
    error.universe, [0, 10, 10]
)


# Output Membership Functions

heater['Low'] = fuzz.trimf(
    heater.universe, [0, 0, 50]
)

heater['Medium'] = fuzz.trimf(
    heater.universe, [0, 50, 100]
)

heater['High'] = fuzz.trimf(
    heater.universe, [50, 100, 100]
)

print("Membership Functions created successfully!")



# Plot Input Membership Functions

error.view()
plt.title("Temperature Error Membership Functions")
plt.show()


# Plot Output Membership Functions

heater.view()
plt.title("Heater Power Membership Functions")
plt.show()



# Define Fuzzy Rules

rule1 = ctrl.Rule(
    error['Negative'], heater['Low']
)

rule2 = ctrl.Rule(
    error['Zero'], heater['Medium']
)

rule3 = ctrl.Rule(
    error['Positive'], heater['High']
)

# Create Fuzzy Control System

system = ctrl.ControlSystem([
    rule1, rule2, rule3
])

print("Fuzzy Rules created successfully!")



simulation = ctrl.ControlSystemSimulation(system)

target_temp = 23
current_temp = 17

temperature_error = target_temp - current_temp

simulation.input['error'] = temperature_error

simulation.compute()

heater_power = simulation.output['heater']

print("Target Temperature:", target_temp)
print("Current Temperature:", current_temp)
print("Temperature Error:", temperature_error)
print("Heater Power:", round(heater_power, 2), "%")


